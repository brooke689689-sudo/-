const CATEGORY_EMOJI: Record<string, string> = {
  dog: "🐶",
  cat: "🐱",
  small: "🐹",
  bird: "🐦",
  reptile: "🦎",
  fish: "🐠",
};

export function breedEmoji(name: string, categorySlug?: string) {
  if (BREED_EMOJI[name]) return BREED_EMOJI[name];
  if (name.includes("햄스터")) return "🐹";
  if (name.includes("앵무") || name.includes("잉꼬")) return "🦜";
  if (name.includes("게코") || name.includes("도마뱀")) return "🦎";
  if (name.includes("뱀") || name.includes("파이톤") || name.includes("스네이크")) return "🐍";
  if (name.includes("거북")) return "🐢";
  if (name.includes("개구리")) return "🐸";
  if (name.includes("토끼")) return "🐰";
  return (categorySlug && CATEGORY_EMOJI[categorySlug]) || "🐾";
}

export function categoryEmoji(slug?: string) {
  return (slug && CATEGORY_EMOJI[slug]) || "🐾";
}
