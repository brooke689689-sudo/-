with ranked as (
  select id, row_number() over (
    partition by category_id
    order by (name like '기타%'), name collate "ko-KR-x-icu"
  ) as ord
  from public.breeds
  where is_banned = false
)
update public.breeds b
set sort_order = r.ord
from ranked r
where b.id = r.id;
