export function generateStaticParams() {
  return Object.keys(DOCS).map((slug) => ({ slug }));
}

export default async function PolicyPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const doc = DOCS[slug];
  if (!doc) notFound();

  return (
    <main className="mx-auto max-w-2xl px-4 py-10">
      <nav className="flex flex-wrap gap-2 text-xs">
        {Object.entries(DOCS).map(([s, d]) => (
          <Link
            key={s}
            href={`/policy/${s}`}
            className={`rounded-full px-3 py-1.5 font-semibold ${s === slug ? "bg-ink text-white" : "bg-white text-stone-500 ring-1 ring-stone-200"}`}
          >
            {d.title}
          </Link>
        ))}
      </nav>
      <h1 className="mt-6 text-2xl font-bold text-ink">{doc.title}</h1>
      {doc.intro && <p className="mt-2 text-sm leading-6 text-stone-600">{doc.intro}</p>}
      <div className="mt-6 space-y-6 rounded-2xl border border-stone-200 bg-white p-6">
        {doc.sections.map((s) => (
          <section key={s.h}>
            <h2 className="font-bold text-stone-900">{s.h}</h2>
            {s.p.map((para, i) =>
              Array.isArray(para) ? (
                <ul key={i} className="mt-2 list-disc space-y-1 pl-5 text-sm leading-6 text-stone-700">
                  {para.map((li) => (
                    <li key={li}>{li}</li>
                  ))}
                </ul>
              ) : (
                <p key={i} className="mt-2 text-sm leading-7 text-stone-700">
                  {para}
                </p>
              ),
            )}
          </section>
        ))}
      </div>
      <p className="mt-4 text-xs text-stone-400">시행일 {POLICY_VERSION} · 정식 출시 전 법률 검토를 거쳐 확정돼요.</p>
    </main>
  );
}
